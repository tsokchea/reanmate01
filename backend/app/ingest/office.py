def _slide_paths(zip_files):
    """Slide order from the presentation's relationships; numeric file order as a fallback."""
    presentation = _text_of(zip_files, "ppt/presentation.xml")
    rels_xml = _text_of(zip_files, "ppt/_rels/presentation.xml.rels")

    if presentation and rels_xml:
        relationships = {}
        for rel in re.findall(r"<Relationship\s[^>]*/?>", rels_xml):
            rel_id, target = _attribute(rel, "Id"), _attribute(rel, "Target")
            if rel_id and target:
                relationships[rel_id] = re.sub(r"^/", "", re.sub(r"^\.\./", "", target))
        ordered = []
        for sld_id in re.findall(rf"<{_PREFIX}sldId\s[^>]*/?>", presentation):
            rel_id = _attribute(sld_id, "r:id") or _attribute(sld_id, "id")
            target = relationships.get(rel_id) if rel_id else None
            if target:
                ordered.append(target if target.startswith("ppt/") else f"ppt/{target}")
        if ordered:
            return ordered

    paths = [path for path in zip_files if re.fullmatch(r"ppt/slides/slide\d+\.xml", path)]
    return sorted(paths, key=lambda path: int(re.search(r"(\d+)\.xml$", path).group(1)))


def _notes_for(zip_files, slide_path):
    """Speaker notes through the slide's own relationships — never by matching numbers."""
    name = slide_path.split("/")[-1]
    rels_xml = _text_of(zip_files, f"ppt/slides/_rels/{name}.rels")
    if not rels_xml:
        return None
    for rel in re.findall(r"<Relationship\s[^>]*/?>", rels_xml):
        if not re.search(r"notesSlide$", _attribute(rel, "Type") or ""):
            continue
        target = _attribute(rel, "Target")
        if not target:
            continue
        path = re.sub(r"^/", "", re.sub(r"^\.\./", "ppt/", target))
        return _text_of(zip_files, path if path.startswith("ppt/") else f"ppt/slides/{path}")
    return None


def _extract_pptx(zip_files):
    sections = []
    for index, path in enumerate(_slide_paths(zip_files)):
        xml = _text_of(zip_files, path)
        if xml is None:
            continue
        lines = [line for line in (_collapse("".join(_text_runs(p, "t"))) for p in _elements(xml, "p")) if line]

        slide_number = index + 1
        notes_xml = _notes_for(zip_files, path)
        notes = []
        if notes_xml:
            notes = [line for line in (_collapse("".join(_text_runs(p, "t"))) for p in _elements(notes_xml, "p"))
                     # PowerPoint puts the slide number itself in the notes placeholder.
                     if line and line != str(slide_number)]

        body = js_trim("\n".join(part for part in [
            "\n".join(lines),
            f"Speaker notes: {' '.join(notes)}" if notes else "",
        ] if part))

        if body:
            # Numbered by POSITION IN THE DECK: a picture-only slide must not shift the rest.
            sections.append({"number": slide_number, "title": lines[0] if lines else None, "text": body})
    return sections



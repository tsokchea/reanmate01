"""Text extraction for Office documents and plain text (server/src/ingest/office.js).

Word, Excel and PowerPoint are all a ZIP of XML parts (OOXML), so they share
one reader built on the standard library's zipfile. Each extractor returns
numbered ``sections`` that chunk exactly like PDF pages, so "slide 12" works
the way "page 12" does.

XML is read with regular expressions rather than a parser. That works because
these parts are machine-generated by Office and only the text runs are pulled
out — no attributes to resolve, no namespaces to honour, no structure to
rebuild. A real XML parser is the right call the moment that stops being true.
"""

import datetime as dt
import io
import re
import zipfile

from ..utils.js import is_integer, js_trim, parse_float, parse_int
from .errors import INGEST_ERROR_CODES, IngestError

FREE_SECTION_LIMIT = 50

PLAIN_TEXT_MIME_TYPES = {"text/plain", "text/markdown", "text/csv"}

# `unit` is the word a student sees for a numbered part; "page 4" of a
# spreadsheet means nothing. `limitUnit` is the plural for the limit message.
OFFICE_FORMATS = {
    "docx": {"mimeType": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
             "label": "Word document", "unit": "section", "limitUnit": "sections"},
    "xlsx": {"mimeType": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
             "label": "Excel spreadsheet", "unit": "sheet", "limitUnit": "sheets"},
    "pptx": {"mimeType": "application/vnd.openxmlformats-officedocument.presentationml.presentation",
             "label": "PowerPoint presentation", "unit": "slide", "limitUnit": "slides"},
    "text": {"mimeType": "text/plain", "label": "Text file", "unit": "section", "limitUnit": "sections"},
}

_PREFIX = r"(?:[a-zA-Z0-9]+:)?"

# ---------------------------------------------------------------------------
# XML helpers
# ---------------------------------------------------------------------------


def _decode_entities(text):
    """The five predefined entities plus numeric references; &amp; LAST so &amp;lt; stays "&lt;"."""
    text = str(text).replace("&lt;", "<").replace("&gt;", ">").replace("&quot;", '"').replace("&apos;", "'")
    text = re.sub(r"&#x([0-9a-fA-F]+);", lambda m: chr(int(m.group(1), 16)), text)
    text = re.sub(r"&#(\d+);", lambda m: chr(int(m.group(1), 10)), text)
    return text.replace("&amp;", "&")


def _text_runs(xml, tag):
    """The text of every <tag>...</tag>, with an optional namespace prefix, in document order."""
    pattern = re.compile(rf"<{_PREFIX}{tag}(?:\s[^>]*)?>([\s\S]*?)</{_PREFIX}{tag}>")
    return [_decode_entities(match.group(1)) for match in pattern.finditer(xml)]


def _elements(xml, tag):
    """The elements named ``tag``, markup included."""
    pattern = re.compile(rf"<{_PREFIX}{tag}(?:\s[^>]*)?>[\s\S]*?</{_PREFIX}{tag}>")
    return [match.group(0) for match in pattern.finditer(xml)]


def _attribute(element, name):
    match = re.search(rf'\s{re.escape(name)}="([^"]*)"', element)
    return match.group(1) if match else None


def _text_of(zip_files, path):
    data = zip_files.get(path)
    return data.decode("utf-8", errors="replace") if data is not None else None


def _collapse(value):
    return js_trim(re.sub(r"\s+", " ", value))


# ---------------------------------------------------------------------------
# Word
# ---------------------------------------------------------------------------


def _extract_docx(zip_files, paragraphs_per_section=40):
    """Word has no pages, so it is divided into numbered SECTIONS of ~40 paragraphs."""
    xml = _text_of(zip_files, "word/document.xml")
    if xml is None:
        raise IngestError(INGEST_ERROR_CODES["EXTRACT_FAILED"],
                          "This Word file is missing its document body and may be corrupt.")

    paragraphs = []
    for paragraph in _elements(xml, "p"):
        runs = _text_runs(paragraph, "t")
        if not runs:
            continue
        line = _collapse("".join(runs))
        if line:
            paragraphs.append(line)

    sections = []
    for start in range(0, len(paragraphs), paragraphs_per_section):
        body = js_trim("\n".join(paragraphs[start:start + paragraphs_per_section]))
        if body:
            sections.append({"number": len(sections) + 1, "title": None, "text": body})
    return sections



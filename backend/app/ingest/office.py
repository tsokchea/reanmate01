def _extract_plain_text(data):
    """Plain text is one section; there are no numbered parts to cite."""
    text = js_trim(data.decode("utf-8", errors="replace").replace("\r\n", "\n"))
    return [{"number": 1, "title": None, "text": text}] if text else []


# ---------------------------------------------------------------------------
# Format detection and entry point
# ---------------------------------------------------------------------------


def detect_ooxml_format(zip_files):
    """Identifies an OOXML package by what is inside it rather than by its name."""
    if "word/document.xml" in zip_files:
        return "docx"
    if "xl/workbook.xml" in zip_files:
        return "xlsx"
    if "ppt/presentation.xml" in zip_files:
        return "pptx"
    return None


def format_for_mime_type(mime_type):
    if mime_type in PLAIN_TEXT_MIME_TYPES:
        return "text"
    return next((key for key, fmt in OFFICE_FORMATS.items() if fmt["mimeType"] == mime_type), None)


def _unzip(data):
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        return {info.filename: archive.read(info) for info in archive.infolist() if not info.is_dir()}


def extract_document(source, mime_type=None, plan_tier="free"):
    """Extracts a document from a path or bytes into numbered sections plus full text."""
    if isinstance(source, (bytes, bytearray)):
        data = bytes(source)
    else:
        with open(source, "rb") as handle:
            data = handle.read()

    if len(data) == 0:
        raise IngestError(INGEST_ERROR_CODES["EXTRACT_FAILED"], "This file is empty. Please upload it again.")

    claimed = format_for_mime_type(mime_type)
    fmt = claimed
    if claimed == "text":
        sections = _extract_plain_text(data)
    else:
        try:
            zip_files = _unzip(data)
        except Exception as err:
            raise IngestError(
                INGEST_ERROR_CODES["EXTRACT_FAILED"],
                f"This file could not be opened — it may be corrupt or password-protected ({err}).",
            ) from err

        # What the package actually is beats what the upload claimed.
        fmt = detect_ooxml_format(zip_files)
        if not fmt:
            raise IngestError(INGEST_ERROR_CODES["EXTRACT_FAILED"],
                              "This does not look like a Word, Excel or PowerPoint file.")
        sections = {"docx": _extract_docx, "xlsx": _extract_xlsx, "pptx": _extract_pptx}[fmt](zip_files)

    info = OFFICE_FORMATS[fmt]
    if not sections:
        raise IngestError(INGEST_ERROR_CODES["EMPTY_CONTENT"],
                          f"No readable text could be found in this {info['label'].lower()}.")

    # Charged against the same free-plan allowance a PDF's pages are, checked
    # after extraction because these formats do not record a part count.
    if plan_tier != "plus" and len(sections) > FREE_SECTION_LIMIT:
        raise IngestError(
            INGEST_ERROR_CODES["PAGE_LIMIT_EXCEEDED"],
            f"Free plan allows up to {FREE_SECTION_LIMIT} {info['limitUnit']} per document "
            f"(this one has {len(sections)}). Please upgrade to Plus for larger documents.",
            {"sectionCount": len(sections), "limit": FREE_SECTION_LIMIT, "unit": info["unit"]},
        )

    full_text = js_trim("\n\n".join(section["text"] for section in sections))
    if not full_text:
        raise IngestError(INGEST_ERROR_CODES["EMPTY_CONTENT"],
                          f"No readable text could be found in this {info['label'].lower()}.")

    return {"format": fmt, "label": info["label"], "unit": info["unit"], "sectionCount": len(sections),
            "sections": sections, "fullText": full_text}

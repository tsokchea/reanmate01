# Excel
# ---------------------------------------------------------------------------


def _shared_strings(zip_files):
    xml = _text_of(zip_files, "xl/sharedStrings.xml")
    if not xml:
        return []
    # One <si> may hold several formatted <t> runs; they are one string.
    return ["".join(_text_runs(si, "t")) for si in _elements(xml, "si")]


BUILTIN_DATE_FORMATS = {14, 15, 16, 17, 18, 19, 20, 21, 22, 45, 46, 47}


def _date_format_ids(zip_files):
    """Style indices whose number format is a date (built-in ids or custom date tokens)."""
    xml = _text_of(zip_files, "xl/styles.xml")
    if not xml:
        return set()

    custom = set()
    for num_fmts in _elements(xml, "numFmts"):
        for fmt in re.findall(rf"<{_PREFIX}numFmt\s[^>]*/>", num_fmts):
            fmt_id = parse_int(_attribute(fmt, "numFmtId") or "")
            code = _attribute(fmt, "formatCode") or ""
            # Strip quoted literals so the "m" in a label like "Month" does not count.
            without_literals = re.sub(r'"[^"]*"', "", code)
            if re.search(r"[dmyhs]", without_literals, re.IGNORECASE) and not re.fullmatch(r"[#0.,%\s]*", without_literals):
                custom.add(fmt_id)

    cell_xfs = (_elements(xml, "cellXfs") or [""])[0]
    styles = [parse_int(_attribute(xf, "numFmtId") or "0") for xf in re.findall(rf"<{_PREFIX}xf\s[^>]*/?>", cell_xfs)]
    return {index for index, fmt_id in enumerate(styles) if fmt_id in BUILTIN_DATE_FORMATS or fmt_id in custom}


# Excel's day 0 is 1899-12-30 (it absorbs Lotus 1-2-3's leap-year bug).
EXCEL_EPOCH_MS = -2209161600000
_UNIX_EPOCH = dt.datetime(1970, 1, 1, tzinfo=dt.timezone.utc)


def _serial_to_date(serial):
    if serial != serial:  # NaN
        return "NaN"
    try:
        ms = int(EXCEL_EPOCH_MS + serial * 86_400_000)  # Date truncates towards zero
        value = _UNIX_EPOCH + dt.timedelta(milliseconds=ms)
    except (OverflowError, ValueError):
        return str(serial)
    iso = f"{value:%Y-%m-%dT%H:%M}"
    # A whole number is a date; a fraction carries a time of day worth keeping.
    return iso[:10] if is_integer(serial) else iso.replace("T", " ")


def _column_of(reference):
    match = re.match(r"^([A-Z]+)", reference or "")
    return match.group(1) if match else ""


def _row_of(reference):
    match = re.search(r"(\d+)$", reference or "")
    return int(match.group(1)) if match else 0


def _extract_sheet(xml, strings, date_styles):
    """One sheet becomes tab-separated lines — tabs, because cell values contain commas."""
    lines = []
    cell_pattern = re.compile(rf"<{_PREFIX}c(?:\s[^>]*)?(?:/>|>[\s\S]*?</{_PREFIX}c>)")
    for row in _elements(xml, "row"):
        cells = []
        for cell in cell_pattern.findall(row):
            kind = _attribute(cell, "t")
            style_index = parse_int(_attribute(cell, "s") or "")
            reference = _attribute(cell, "r")

            if kind == "s":
                index = parse_int((_text_runs(cell, "v") or [""])[0])
                value = strings[index] if index is not None and 0 <= index < len(strings) else ""
            elif kind == "inlineStr":
                value = "".join(_text_runs(cell, "t"))
            elif kind == "str":
                value = (_text_runs(cell, "v") or [""])[0]
            elif kind == "b":
                value = "TRUE" if (_text_runs(cell, "v") or [None])[0] == "1" else "FALSE"
            else:
                runs = _text_runs(cell, "v")
                if not runs:
                    value = ""
                elif style_index is not None and style_index in date_styles and runs[0] != "":
                    value = _serial_to_date(parse_float(runs[0]))
                else:
                    value = runs[0]

            if value != "":
                cells.append({"column": _column_of(reference), "value": _collapse(str(value))})

        if cells:
            lines.append({"row": _row_of(_attribute(row, "r")), "text": "\t".join(c["value"] for c in cells)})

    return "\n".join(line["text"] for line in lines if line["text"].strip())


def _extract_xlsx(zip_files):
    """Sheet order comes from workbook.xml and its relationships, never from file names."""
    workbook = _text_of(zip_files, "xl/workbook.xml")
    if workbook is None:
        raise IngestError(INGEST_ERROR_CODES["EXTRACT_FAILED"],
                          "This Excel file is missing its workbook and may be corrupt.")

    strings = _shared_strings(zip_files)
    date_styles = _date_format_ids(zip_files)

    rels_xml = _text_of(zip_files, "xl/_rels/workbook.xml.rels") or ""
    relationships = {}
    for rel in re.findall(r"<Relationship\s[^>]*/?>", rels_xml):
        rel_id, target = _attribute(rel, "Id"), _attribute(rel, "Target")
        if rel_id and target:
            relationships[rel_id] = re.sub(r"^/", "", re.sub(r"^/?xl/", "", target))

    sections = []
    for index, sheet in enumerate(re.findall(rf"<{_PREFIX}sheet\s[^>]*/?>", workbook)):
        name = _attribute(sheet, "name") or f"Sheet{index + 1}"
        rel_id = _attribute(sheet, "r:id") or _attribute(sheet, "id")
        target = relationships.get(rel_id) if rel_id else None
        sheet_xml = _text_of(zip_files, f"xl/{target or f'worksheets/sheet{index + 1}.xml'}")
        if sheet_xml is None:
            continue
        body = _extract_sheet(sheet_xml, strings, date_styles)
        if body.strip():
            # Numbered by position in the workbook, so an empty sheet never renumbers the rest.
            sections.append({"number": index + 1, "title": name, "text": f"{name}\n{body}"})
    return sections


